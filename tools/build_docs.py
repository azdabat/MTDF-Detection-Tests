#!/usr/bin/env python3
"""
build_docs.py - generate the showcase documentation from the repository itself.

Reads   detections/<tactic>/<detection>/detection.yml   (metadata)
        detections/<tactic>/<detection>/*.yml             (tests)
        docs/results.json                                 (last run, written by run_tests.py --json)
Writes  detections/<tactic>/<detection>/README.md         (one page per detection)
        README.md, between <!-- COVERAGE:START --> and <!-- COVERAGE:END -->
        docs/attack-navigator-layer.json                  (MITRE ATT&CK Navigator layer)

Nothing here is hand-maintained: edit detection.yml / test files and rebuild.

    python tools/build_docs.py
    python tools/build_docs.py --results docs/results.json --repo azdabat/MTDF-Detection-Tests
"""
import argparse
import glob
import json
import os
import re
import sys
import urllib.parse

import yaml

import attack_tactics as at

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
START, END = "<!-- COVERAGE:START -->", "<!-- COVERAGE:END -->"
GENERATED = "<!-- Generated by tools/build_docs.py from detection.yml, the test files and docs/results.json. Edit those, not this file. -->"
ICON = {"pass": "✅ Pass", "fail": "❌ Fail", "error": "💥 Error", "known": "⚠️ Boundary", None: "⏳ Not run"}


def tlink(t):
    t = t.strip()
    path = t.replace(".", "/")
    return f"[{t}](https://attack.mitre.org/techniques/{path}/)"


def implementation(source, mark_synthetic=False):
    """Tool that produced the capture. Real captures with a few added synthetic rows keep their tool label."""
    s = source.lower()
    label = "Synthetic"
    for key, name in (("empire_", "Empire"), ("covenant_", "Covenant"), ("cmd_psexec", "Sysinternals PsExec"),
                      ("cmd_", "Native cmd"), ("psh_", "Native PowerShell"), ("schtask", "Native schtasks")):
        if key in s:
            label = name
            break
    else:
        if "synthetic" not in s:
            label = "OTRF"
    if mark_synthetic and "synthetic" in s and label != "Synthetic":
        label += " + synthetic row"
    return label


def load_detections():
    dets = []
    for meta_file in sorted(glob.glob(os.path.join(ROOT, "detections", "*", "*", "detection.yml"))):
        folder = os.path.dirname(meta_file)
        tactic, name = os.path.relpath(folder, os.path.join(ROOT, "detections")).split(os.sep)
        meta = yaml.safe_load(open(meta_file, encoding="utf-8")) or {}
        tests = []
        for tf in sorted(glob.glob(os.path.join(folder, "*.yml"))):
            if os.path.basename(tf) == "detection.yml":
                continue
            case = yaml.safe_load(open(tf, encoding="utf-8")) or {}
            case["_file"] = os.path.basename(tf)
            case["_rel"] = f"{tactic}/{name}/{case['_file']}"
            tests.append(case)
        rule = next(iter(sorted(glob.glob(os.path.join(folder, "*.kql")))), None)
        dets.append({"tactic": tactic, "name": name, "folder": folder, "meta": meta, "tests": tests,
                     "rule": os.path.basename(rule) if rule else None})
    return dets


def detection_status(det, res):
    """(icon_label, sort_key) for a detection given test results."""
    runs = [res.get(t["_rel"]) for t in det["tests"]]
    if not any(runs):
        return "⏳ Awaiting first run", 3
    stable = [r for t, r in zip(det["tests"], runs) if r and r["maturity"] == "stable"]
    if any(r["status"] in ("fail", "error") for r in stable):
        return "❌ Failing", 4
    real = [r for r in runs if r and r["status"] != "known"]
    passed = sum(1 for r in real if r["status"] == "pass")
    if not real:
        return "⚠️ Boundary documented (no passing implementation)", 2
    if stable and all(r["status"] == "pass" for r in stable):
        return f"✅ Validated ({passed}/{len(real)} implementations)", 0
    return f"🧪 In validation ({passed}/{len(real)} passing)", 1


def write_detection_readme(det, res, repo):
    m, tests = det["meta"], det["tests"]
    status, _ = detection_status(det, res)
    techs = " · ".join(tlink(t) for t in m.get("techniques", []))
    lines = [GENERATED, "", f"# {m.get('title', det['name'])}", "",
             f"**Tactic:** {at.DISPLAY.get(det['tactic'], det['tactic'])} · **ATT&CK:** {techs}  ",
             f"**Status:** {status}  ",
             f"**Data:** {', '.join('`'+d+'`' for d in m.get('data_sources', []))} · "
             f"**Platforms:** {', '.join(m.get('platforms', []))} · **Production lookback:** {m.get('production_lookback', '?')}  ",
             f"**Rule:** [`{det['rule']}`]({det['rule']}) · **Author:** {m.get('author', '')}", "",
             "## Minimum truth", "", f"> {m.get('minimum_truth', '_not stated_')}", ""]
    if m.get("reinforcement"):
        lines += ["## Reinforcement", "", m["reinforcement"], ""]
    lines += ["## Validation against real adversary telemetry", "",
              "| Test | Implementation | Telemetry | Must catch | Maturity | Last result |",
              "|---|---|---|---|---|---|"]
    boundaries = []
    for t in tests:
        r = res.get(t["_rel"])
        src = str(t.get("source", "")).replace("OTRF ", "").replace("Security-Datasets - ", "")
        src_md = f"[`{src}`]({t['source_url']})" if t.get("source_url") else f"`{src}`"
        result = ICON[r["status"]] if r else ICON[None]
        if r and r["status"] == "pass":
            result += f" ({r['rows']} rows)"
        catches = str(t.get("catches", "")).replace("|", "\\|")
        lines.append(f"| [`{t['_file']}`]({t['_file']}) | {implementation(src, True)} | {src_md} | {catches} | "
                     f"{t.get('maturity', 'stable')} | {result} |")
        if t.get("known_issue"):
            boundaries.append((t["_file"], t["known_issue"]))
    if boundaries:
        lines += ["", "## Known coverage boundaries", "",
                  "Documented cases where this implementation of the technique does not produce the rule's minimum truth. "
                  "They run on every build and will report when a rule change closes the gap.", ""]
        lines += [f"- **`{f}`**: {why}" for f, why in boundaries]
    lines += ["", "## Run it", "", "```bash",
              f"python tools/run_tests.py -k {det['tactic']}/{det['name']}",
              f"python tools/run_tests.py -k {det['tactic']}/{det['name']}/{tests[0]['_file'] if tests else 'test.yml'} --out query.kql   # paste into ADX",
              "```", "",
              "The rule in this folder is the **lab build**: identical detection logic, with the lookback widened so the "
              f"2019-2020 captures fall inside it (production: {m.get('production_lookback', '?')}). "
              "See [methodology](../../../docs/methodology.md) for how tests run and what the telemetry can and cannot represent.", ""]
    with open(os.path.join(det["folder"], "README.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))


def coverage_block(dets, res, run_utc, repo):
    rows, boundaries, impls = [], [], set()
    tactics = set()
    real_pass = 0
    for d in dets:
        status, key = detection_status(d, res)
        tactics.add(d["tactic"])
        passed_impl = sorted({implementation(str(t.get("source", ""))) for t in d["tests"]
                              if res.get(t["_rel"], {}).get("status") == "pass"})
        impls.update(passed_impl)
        real_pass += sum(1 for t in d["tests"] if res.get(t["_rel"], {}).get("status") == "pass")
        techs = ", ".join(tlink(t) for t in d["meta"].get("techniques", []))
        title = re.sub(r"\s*\(Composite[^)]*\)", "", d["meta"].get("title", d["name"]))
        rows.append((at.ORDER.get(d["tactic"], 99), key, f"| {at.DISPLAY.get(d['tactic'], d['tactic'])} | "
                     f"[{title}](detections/{d['tactic']}/{d['name']}) | {techs} | "
                     f"{', '.join(passed_impl) or '-'} | {status} |"))
        boundaries += [f"- **{title}** · `{t['_file']}`: {t['known_issue']}" for t in d["tests"] if t.get("known_issue")]
    rows.sort()
    head = (f"**{len(dets)} detections** across **{len(tactics)} of {len(at.TACTICS)}** ATT&CK tactics · "
            f"**{real_pass}** tests passing on recorded adversary telemetry · implementations proven: "
            f"{', '.join(sorted(impls)) or '-'}")
    if run_utc:
        head += f"  \n_Last test run: {run_utc}_"
    lines = [head, "", "| Tactic | Detection | ATT&CK | Proven against | Status |", "|---|---|---|---|---|"]
    lines += [r[2] for r in rows]
    if boundaries:
        lines += ["", "<details><summary><b>Known coverage boundaries</b> (" + str(len(boundaries)) +
                  ") - documented, tested on every build</summary>", ""] + boundaries + ["", "</details>"]
    if repo:
        raw = f"https://raw.githubusercontent.com/{repo}/main/docs/attack-navigator-layer.json"
        nav = "https://mitre-attack.github.io/attack-navigator/#layerURL=" + urllib.parse.quote(raw, safe="")
        lines += ["", f"🗺️ **[Open the coverage map in MITRE ATT&CK Navigator]({nav})** "
                      "(green = validated in CI, amber = in validation)"]
    return "\n".join(lines)


def navigator_layer(dets, res):
    best = {}
    for d in dets:
        status, key = detection_status(d, res)
        score = 2 if key == 0 else 1
        for t in d["meta"].get("techniques", []):
            cur = best.get(t)
            note = f"{d['meta'].get('title', d['name'])} - {status}"
            if not cur or score > cur["score"]:
                best[t] = {"score": score, "notes": [note]}
            elif score == cur["score"]:
                cur["notes"].append(note)
    green, amber = "#4caf50", "#ffb74d"
    techniques = []
    for tid, v in sorted(best.items()):
        techniques.append({"techniqueID": tid, "score": v["score"], "color": green if v["score"] == 2 else amber,
                           "comment": " | ".join(v["notes"]), "enabled": True, "showSubtechniques": False})
    for parent in sorted({t.split(".")[0] for t in best if "." in t} - set(best)):
        techniques.append({"techniqueID": parent, "enabled": True, "showSubtechniques": True})
    return {
        "name": "MTDF - detection coverage tested against adversary telemetry",
        "versions": {"attack": "17", "navigator": "5.1.0", "layer": "4.5"},
        "domain": "enterprise-attack",
        "description": "Generated by tools/build_docs.py. Green: validated in CI against recorded attack telemetry. "
                       "Amber: in validation.",
        "filters": {"platforms": ["Windows"]},
        "sorting": 0,
        "layout": {"layout": "side", "aggregateFunction": "max", "showID": True, "showName": True,
                   "showAggregateScores": False, "countUnscored": False},
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": ["#ffffff", green], "minValue": 0, "maxValue": 2},
        "legendItems": [{"label": "Validated in CI", "color": green}, {"label": "In validation", "color": amber}],
        "showTacticRowBackground": False,
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "docs", "results.json"))
    ap.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "azdabat/MTDF-Detection-Tests"),
                    help="owner/name, used for the ATT&CK Navigator link")
    args = ap.parse_args()

    res, run_utc = {}, None
    if os.path.exists(args.results):
        data = json.load(open(args.results, encoding="utf-8"))
        res = {t["test"]: t for t in data.get("tests", [])}
        run_utc = data.get("run_utc")

    dets = load_detections()
    if not dets:
        print("no detections with a detection.yml found")
        return 1
    for d in dets:
        write_detection_readme(d, res, args.repo)

    readme = os.path.join(ROOT, "README.md")
    text = open(readme, encoding="utf-8").read()
    if START in text and END in text:
        block = coverage_block(dets, res, run_utc, args.repo)
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: f"{START}\n{block}\n{END}", text, flags=re.S)
        open(readme, "w", encoding="utf-8").write(text)
    else:
        print(f"README.md has no {START}/{END} markers - coverage table not written")

    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "attack-navigator-layer.json"), "w", encoding="utf-8") as fh:
        json.dump(navigator_layer(dets, res), fh, indent=1)

    print(f"docs built: {len(dets)} detection pages, README coverage, ATT&CK Navigator layer"
          + (f" (results from {run_utc})" if run_utc else " (no results yet)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
